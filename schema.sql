-- AI 起名平台 建表脚本
-- 使用方式：Supabase 控制台 → SQL Editor → 粘贴执行

create table if not exists name_history (
  id bigint generated by default as identity primary key,
  user_requirement text not null,
  name_result text not null,
  model_name text not null,
  created_at timestamp with time zone default now()
);

-- 按时间倒序查询的索引
create index if not exists name_history_created_at_idx
  on name_history (created_at desc);

-- 开启行级安全（RLS）
alter table name_history enable row level security;

-- 演示用：放行匿名读写（正式上线应改为按登录用户隔离的策略，
-- 例如使用 auth.uid() 限制只有本人可读写自己的记录）
create policy "anon insert name_history" on name_history
  for insert with check (true);

create policy "anon select name_history" on name_history
  for select using (true);

create policy "anon update name_history" on name_history
  for update using (true) with check (true);

create policy "anon delete name_history" on name_history
  for delete using (true);
